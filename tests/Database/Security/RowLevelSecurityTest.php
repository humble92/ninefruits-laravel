<?php

/*
| Row level security proof of concept (porting/decisions/0003-row-level-security.md).
| Two tables shaped like student_records and enrollments, with the policy pattern
| planned for Phase 2: owner, global permission holder, system context.
*/

use App\Domain\Security\Enums\Permission;
use App\Models\User;
use App\Support\Database\DatabaseSessionContext;
use Illuminate\Contracts\Queue\ShouldQueue;
use Illuminate\Foundation\Queue\Queueable;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Route;

class CountRlsPocRecords implements ShouldQueue
{
    use Queueable;

    public static ?int $seen = null;

    public function handle(): void
    {
        self::$seen = DB::table('rls_poc_student_records')->count();
    }
}

function rlsContext(): DatabaseSessionContext
{
    return app(DatabaseSessionContext::class);
}

beforeEach(function () {
    $owner = DB::connection(config('database.migrator_connection'));

    // Created outside the test transaction; dropped at the start of the next test.
    $owner->unprepared(<<<'SQL'
        DROP TABLE IF EXISTS rls_poc_enrollments, rls_poc_student_records;

        CREATE TABLE rls_poc_student_records (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id bigint NOT NULL,
            student_number text NOT NULL
        );
        CREATE TABLE rls_poc_enrollments (
            id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            student_record_id bigint NOT NULL REFERENCES rls_poc_student_records (id),
            grade text
        );
        CREATE INDEX ON rls_poc_student_records (user_id);
        CREATE INDEX ON rls_poc_enrollments (student_record_id);

        ALTER TABLE rls_poc_student_records ENABLE ROW LEVEL SECURITY;
        ALTER TABLE rls_poc_enrollments ENABLE ROW LEVEL SECURITY;

        CREATE POLICY rls_poc_student_records_owner_select ON rls_poc_student_records
            FOR SELECT USING (user_id = (SELECT util.current_user_id()));
        CREATE POLICY rls_poc_student_records_staff_all ON rls_poc_student_records
            FOR ALL USING ((SELECT util.has_permission('users.view'))) WITH CHECK ((SELECT util.has_permission('users.view')));
        CREATE POLICY rls_poc_student_records_system_all ON rls_poc_student_records
            FOR ALL USING ((SELECT util.is_system_context())) WITH CHECK ((SELECT util.is_system_context()));

        CREATE POLICY rls_poc_enrollments_owner_select ON rls_poc_enrollments
            FOR SELECT USING (student_record_id IN (
                SELECT sr.id FROM rls_poc_student_records AS sr WHERE sr.user_id = (SELECT util.current_user_id())
            ));
        CREATE POLICY rls_poc_enrollments_staff_all ON rls_poc_enrollments
            FOR ALL USING ((SELECT util.has_permission('users.view'))) WITH CHECK ((SELECT util.has_permission('users.view')));
        CREATE POLICY rls_poc_enrollments_system_all ON rls_poc_enrollments
            FOR ALL USING ((SELECT util.is_system_context())) WITH CHECK ((SELECT util.is_system_context()));
        SQL);

    $this->alice = User::factory()->create();
    $this->bob = User::factory()->create();

    rlsContext()->forSystem('test:seed');
    foreach ([$this->alice, $this->bob] as $index => $user) {
        $recordId = DB::table('rls_poc_student_records')->insertGetId(['user_id' => $user->id, 'student_number' => "2026000{$index}"]);
        DB::table('rls_poc_enrollments')->insert([['student_record_id' => $recordId, 'grade' => 'A'], ['student_record_id' => $recordId, 'grade' => 'B']]);
    }
    rlsContext()->useBaseline([]);
});

it('shows users only their own rows, including in related tables', function () {
    rlsContext()->forUser($this->alice->id);

    expect(DB::table('rls_poc_student_records')->pluck('user_id')->all())->toBe([$this->alice->id])
        ->and(DB::table('rls_poc_enrollments')->count())->toBe(2);

    rlsContext()->forUser($this->bob->id);

    expect(DB::table('rls_poc_student_records')->pluck('user_id')->all())->toBe([$this->bob->id]);
});

it('returns nothing without a request context', function () {
    expect(DB::table('rls_poc_student_records')->count())->toBe(0)
        ->and(DB::table('rls_poc_enrollments')->count())->toBe(0);
});

it('blocks a direct lookup of another user record even when the id is known', function () {
    rlsContext()->forSystem('test:lookup');
    $bobRecordId = DB::table('rls_poc_student_records')->where('user_id', $this->bob->id)->value('id');
    expect($bobRecordId)->not->toBeNull();

    rlsContext()->forUser($this->alice->id);

    expect(DB::table('rls_poc_student_records')->where('id', $bobRecordId)->first())->toBeNull()
        ->and(DB::table('rls_poc_student_records')->where('id', $bobRecordId)->update(['student_number' => 'x']))->toBe(0);
});

it('lets users with a global permission see every row while the assignment is active', function () {
    $staff = User::factory()->withPermissions([Permission::UsersView])->create();
    rlsContext()->forUser($staff->id);

    expect(DB::table('rls_poc_student_records')->count())->toBe(2);

    $staff->roleAssignments()->update(['ends_at' => now()->subMinute()]);

    expect(DB::table('rls_poc_student_records')->count())->toBe(0);
});

it('does not let users write rows they cannot see', function () {
    rlsContext()->forUser($this->alice->id);

    expect(databaseError(fn () => DB::table('rls_poc_student_records')->insert(['user_id' => $this->alice->id, 'student_number' => 'forged'])))
        ->toContain('row-level security');
});

it('gives queued jobs the system context and clears it afterwards', function () {
    CountRlsPocRecords::dispatch();

    expect(CountRlsPocRecords::$seen)->toBe(2)
        ->and(rlsContext()->current()['app.actor'])->toBe('');
});

it('clears the user context when a request ends, so reused connections start empty', function () {
    Route::middleware('web')->get('/_test/rls-count', fn () => ['count' => DB::table('rls_poc_student_records')->count()]);

    $this->actingAs($this->alice)->get('/_test/rls-count')->assertJson(['count' => 1]);

    expect(DB::table('rls_poc_student_records')->count())->toBe(0);
});
